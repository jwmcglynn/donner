def width_mapping(row: str) -> Optional[tuple[int, int]]:
    """Return a narrow-to-wide pair for a Unicode width decomposition, if present."""
    fields = row.split(";")
    parts = fields[5].split()
    if not parts or parts[0] not in ("<wide>", "<narrow>"):
        return None
    if len(parts) != 2:
        raise ValueError("Width mapping must preserve the codepoint count")
    codepoint, target = int(fields[0], 16), int(parts[1], 16)
    return (target, codepoint) if parts[0] == "<wide>" else (codepoint, target)


def generate(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("UnicodeData input does not match the pinned Unicode 17.0.0 digest")
    mapping = {}
    for row in source.decode("utf-8").splitlines():
        pair = width_mapping(row)
        if pair is None:
            continue
        if pair[0] in mapping:
            raise ValueError("Duplicate width mapping")
        mapping[pair[0]] = pair[1]
    if len(mapping) != 226:
        raise ValueError("Unexpected width mapping count")
    header = "#pragma once\n/// @file\n\n"
    header += "// Generated by tools/unicode/generate_full_width.py; do not edit.\n"
    header += "// Unicode 17.0.0: " + SOURCE_URL + "\n"
    header += "// SHA256: " + SOURCE_SHA256 + "\n//\n"
    header += "\n".join("// " + line if line else "//" for line in LICENSE.splitlines())
    header += "\n\n#include <array>\n#include <cstdint>\n#include <utility>\n\n"
    header += "namespace donner::svg::detail {\n\n"
    header += "inline constexpr std::array<std::pair<char32_t, char32_t>, 226> kFullWidthMapping = {{\n"
    entries = [f"{{0x{key:04x}, 0x{value:04x}}}," for key, value in sorted(mapping.items())]
    header += "".join("    " + " ".join(entries[index:index + 5]) + "\n"
                      for index in range(0, len(entries), 5))
    header += "}};\n\n}  // namespace donner::svg::detail\n"
    return header


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("--output", type=Path, default=Path("donner/svg/text/FullWidthMapping.h"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.unicode_data.read_bytes())
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("Generated full-width table differs from the pinned Unicode source")
        print("Verified 226 Unicode 17.0.0 width mappings")
    else:
        args.output.write_text(result)
        print(f"Wrote 226 mappings ({len(result.encode())} bytes)")


if __name__ == "__main__":
    main()
