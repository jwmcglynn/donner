#!/usr/bin/env python3
"""Generate pinned Unicode 17.0.0 properties for extended grapheme segmentation."""
import argparse
import hashlib
from pathlib import Path

from generate_full_width import LICENSE

INPUTS = {
    "grapheme": ("auxiliary/GraphemeBreakProperty.txt", "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89"),
    "emoji": ("emoji/emoji-data.txt", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"),
    "indic": ("DerivedCoreProperties.txt", "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"),
    "arabic": ("ArabicShaping.txt", "39afa01e680e27d0fd10b67a9b27be13fbaa3d0efecfb5be45991de9a0d267d0"),
    "joining": ("extracted/DerivedJoiningType.txt", "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d"),
}
CONFORMANCE_SHA256 = "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec"
CONFORMANCE_URL = "https://www.unicode.org/Public/17.0.0/ucd/auxiliary/GraphemeBreakTest.txt"
PROPERTIES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
              "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]


def joining_row(fields: list[str], kind: str):
    """Parse potential Arabic ligature groups or transparent joining ranges."""
    bounds = fields[0].split("..")
    first, last = int(bounds[0], 16), int(bounds[-1], 16)
    if kind == "joining":
        return (first, last, 1) if fields[1] == "T" else None
    if len(fields) != 4 or fields[3] not in ("LAM", "ALEF"):
        return None
    # Specialized alefs use original shaped-unit protection rather than this candidate profile.
    if 0x0870 <= first <= 0x0882:
        return None
    return first, last, 1 if fields[3] == "LAM" else 2


def property_row(line: str, kind: str):
    """Parse one relevant UCD range, omitting algorithmic Hangul syllables."""
    fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
    if len(fields) < 2 or not fields[0]:
        return None
    if kind in ("arabic", "joining"):
        return joining_row(fields, kind)
    name = fields[1]
    if kind == "emoji" and name != "Extended_Pictographic":
        return None
    if kind == "indic":
        if name != "InCB" or len(fields) != 3:
            return None
        name = fields[2]
    if kind == "grapheme" and name in ("LV", "LVT"):
        return None
    bounds = fields[0].split("..")
    first, last = int(bounds[0], 16), int(bounds[-1], 16)
    values = PROPERTIES if kind == "grapheme" else ["None", "Consonant", "Extend", "Linker"]
    value = 1 if kind == "emoji" else values.index(name)
    return first, last, value


def ranges(source: bytes, kind: str):
    """Return sorted, coalesced property intervals from a verified input."""
    rows = sorted(row for line in source.decode().splitlines()
                  if (row := property_row(line, kind)) is not None)
    return merge_ranges(rows)


def merge_ranges(rows):
    """Coalesce adjacent intervals carrying the same property value."""
    merged = []
    for first, last, value in rows:
        if merged and first <= merged[-1][1]:
            raise ValueError("Overlapping property intervals")
        if merged and first == merged[-1][1] + 1 and value == merged[-1][2]:
            merged[-1] = merged[-1][0], last, value
        else:
            merged.append((first, last, value))
    return merged


def transparency_overrides(grapheme, joining):
    """Reuse GCB Extend and store only the exact joining-transparency differences."""
    extend = {cp for first, last, value in grapheme if value == 4
              for cp in range(first, last + 1)}
    transparent = {cp for first, last, _ in joining for cp in range(first, last + 1)}
    rows = [(cp, cp, 1 if cp in transparent else 2) for cp in sorted(extend ^ transparent)]
    return merge_ranges(rows)


def generate(directory: Path):
    """Generate compact two-word ranges, retaining source and license provenance."""
    result = "#pragma once\n/// @file\n\n// Generated by tools/unicode/generate_grapheme.py; do not edit.\n"
    tables = {}
    for kind, (url, digest) in INPUTS.items():
        source = (directory / url).read_bytes()
        if hashlib.sha256(source).hexdigest() != digest:
            raise ValueError("Input differs from pinned Unicode 17.0.0 " + kind)
        tables[kind] = ranges(source, kind)
        result += "// https://www.unicode.org/Public/17.0.0/ucd/" + url + "\n"
        result += "// SHA256: " + digest + "\n"
    tables["joining"] = transparency_overrides(tables["grapheme"], tables["joining"])
    result += "//\n" + "\n".join("// " + line if line else "//" for line in LICENSE.splitlines())
    result += "\n\n#include <array>\n#include <cstdint>\n\nnamespace donner::svg::detail {\n\n"
    result += "struct GraphemePropertyRange {\n  uint32_t firstAndValue;\n  uint32_t last;\n};\n\n"
    for kind, rows in tables.items():
        name = "k" + kind.title() + "Ranges"
        result += f"inline constexpr std::array<GraphemePropertyRange, {len(rows)}> {name} = {{{{\n"
        entries = [f"{{0x{first | (value << 21):08x}, 0x{last:06x}}}," for first, last, value in rows]
        columns = 1 if kind == "arabic" else 4
        result += "".join("    " + " ".join(entries[i:i + columns]) + "\n"
                          for i in range(0, len(entries), columns))
        result += "}};\n\n"
    return result + "}  // namespace donner::svg::detail\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path)
    parser.add_argument("--output", type=Path, default=Path("donner/svg/text/GraphemeProperties.h"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    conformance = (args.inputs / "auxiliary/GraphemeBreakTest.txt").read_bytes()
    if hashlib.sha256(conformance).hexdigest() != CONFORMANCE_SHA256:
        raise ValueError("Conformance data differs from pinned Unicode 17.0.0")
    checked_in = Path("donner/svg/text/tests/unicode/GraphemeBreakTest.txt")
    prefix = ("# Source: " + CONFORMANCE_URL + "\n# SHA256: " + CONFORMANCE_SHA256 +
              "\n# Generated with trailing whitespace normalized.\n")
    normalized = prefix + "\n".join(line.rstrip() for line in conformance.decode().splitlines()) + "\n"
    if args.check:
        if checked_in.read_text() != normalized:
            raise ValueError("Checked-in conformance data differs from the pinned source")
    else:
        checked_in.write_text(normalized)
    result = generate(args.inputs)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("Generated grapheme properties differ")
    else:
        args.output.write_text(result)
    print("Verified Unicode 17.0.0 grapheme properties")


if __name__ == "__main__":
    main()
